//! A minimal 8x8 bitmap font.
//!
//! Covers space, digits, uppercase letters and the punctuation the shell
//! actually produces. There is no separate lowercase glyph set: lowercase
//! input renders as its uppercase glyph, the same simplification an early
//! teletype made. Every glyph below was designed as an 8-row `.`/`#` grid,
//! rendered back to a terminal and checked by eye before being converted to
//! bytes, rather than transcribed from memory -- see the generator this table
//! came from if the font ever needs to grow.
//!
