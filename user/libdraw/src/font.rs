/// The rows for a fallback glyph: a hollow box, for anything not in the font.
const FALLBACK: [u8; 8] = [0xfe, 0x82, 0x82, 0x82, 0x82, 0x82, 0xfe, 0x00];

/// Look up the 8 row-bytes for `byte`, falling back to a hollow box for
/// anything printable that has no glyph.
pub fn glyph(byte: u8) -> [u8; 8] {
    // A tab advances one cell in the text grid, which already spaces the line;
    // drawing a box for it would put a visible mark where the gap belongs.
    if byte == b'\t' {
        return [0; 8];
    }
    match GLYPHS.iter().find(|entry| entry.ch == byte) {
        Some(entry) => entry.rows,
        None => FALLBACK,
    }
}
