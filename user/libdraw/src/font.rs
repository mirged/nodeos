/// The rows for a fallback glyph: a hollow box, for anything not in the font.
const FALLBACK: [u8; 8] = [0xfe, 0x82, 0x82, 0x82, 0x82, 0x82, 0xfe, 0x00];

/// Look up the 8 row-bytes for `byte`, folding lowercase to uppercase and
/// falling back to a hollow box for anything else printable.
pub fn glyph(byte: u8) -> [u8; 8] {
    let folded = byte.to_ascii_uppercase();
    match GLYPHS.iter().find(|entry| entry.ch == folded) {
        Some(entry) => entry.rows,
        None => FALLBACK,
    }
}
